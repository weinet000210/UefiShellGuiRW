/** @file
  Common widgets of UefiShellGuiRW: hex grid, bit field view, virtual list,
  tree view, property table, table, text view and modal dialogs, plus the
  keyboard focus chain inside a child window.

  Keyboard input never goes through an LVGL group: RwKeyHandler hands every
  key to the open dialog first, then the menu bar, the global shortcuts, and
  finally the focused widget of the active child window (RwFocusHandleKey).
  Tab / Shift+Tab move the focus between the widgets of a window; a click on
  a widget focuses it.

  Copyright (c) 2026, Niall Tseng. All rights reserved.<BR>
  SPDX-License-Identifier: BSD-2-Clause-Patent
**/

