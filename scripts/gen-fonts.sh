#!/bin/sh
# Regenerate the monospace fonts of the hex grid and text views
# (UefiShellGuiRWPkg/Application/UefiShellGuiRW/Widgets/FontMono*.c) from
# DejaVu Sans Mono with lv_font_conv (https://github.com/lvgl/lv_font_conv).
#
#   scripts/gen-fonts.sh [path/to/DejaVuSansMono.ttf]
#
# DejaVu fonts: Bitstream Vera license (free to use, modify and redistribute).
set -e
TTF="${1:-/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf}"
OUT="$(dirname "$0")/../UefiShellGuiRWPkg/Application/UefiShellGuiRW/Widgets"
for SIZE in 12 14; do
  npx -y lv_font_conv@1.5.3 --font "$TTF" -r 0x20-0x7E,0xB7,0x2026 --size $SIZE --bpp 4 \
    --format lvgl --no-compress --lv-include lvgl.h --lv-font-name gRwFontMono$SIZE \
    -o "$OUT/FontMono$SIZE.c"
  # Headers of generated files: what they are and their license.
  { printf '/* DejaVu Sans Mono %s px, generated by scripts/gen-fonts.sh - do not edit.\n' $SIZE
    printf ' * DejaVu fonts: Bitstream Vera Fonts copyright, free license (see\n'
    printf ' * https://dejavu-fonts.github.io/License.html). */\n\n'
    cat "$OUT/FontMono$SIZE.c"; } > "$OUT/FontMono$SIZE.c.tmp"
  mv "$OUT/FontMono$SIZE.c.tmp" "$OUT/FontMono$SIZE.c"
done
