#!/usr/bin/env python3
"""Generate UefiShellGuiRWPkg/Library/RwCoreLib/RwGuidNames.c: the GUID name
table of the UEFI Handles and UEFI System windows, from edk2 DEC files.

usage: scripts/gen-guids.py <edk2 directory>
"""
import os
import re
import sys

DECS = [
    "MdePkg/MdePkg.dec",
    "MdeModulePkg/MdeModulePkg.dec",
    "UefiCpuPkg/UefiCpuPkg.dec",
    "ShellPkg/ShellPkg.dec",
    "NetworkPkg/NetworkPkg.dec",
    "SecurityPkg/SecurityPkg.dec",
    "OvmfPkg/OvmfPkg.dec",
    "PcAtChipsetPkg/PcAtChipsetPkg.dec",
    "FatPkg/FatPkg.dec",
    "CryptoPkg/CryptoPkg.dec",
]

ENTRY = re.compile(
    r"^\s*(g\w+?)\s*=\s*\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,"
    r"\s*\{\s*((?:0x[0-9a-fA-F]+\s*,\s*){7}0x[0-9a-fA-F]+)\s*\}\s*\}"
)


def pretty(name):
    name = name[1:]
    for suffix in ("Guid",):
        if name.endswith(suffix):
            name = name[: -len(suffix)]
    return name


def main():
    edk2 = sys.argv[1]
    seen = {}
    for dec in DECS:
        path = os.path.join(edk2, dec)
        if not os.path.exists(path):
            continue
        section = ""
        for line in open(path, encoding="utf-8", errors="replace"):
            s = line.strip()
            if s.startswith("["):
                section = s.lower()
                continue
            if not (section.startswith("[guids") or section.startswith("[protocols") or section.startswith("[ppis")):
                continue
            if section.startswith("[ppis"):
                continue
            m = ENTRY.match(line)
            if not m:
                continue
            name = pretty(m.group(1))
            d1, d2, d3 = (int(m.group(i), 16) for i in (2, 3, 4))
            d4 = tuple(int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", m.group(5)))
            key = (d1, d2, d3, d4)
            if key not in seen:
                seen[key] = name
    out = os.path.join(os.path.dirname(__file__), "..", "UefiShellGuiRWPkg", "Library", "RwCoreLib", "RwGuidNames.c")
    rows = sorted(seen.items(), key=lambda kv: kv[1].lower())
    with open(out, "w", newline="\n") as f:
        f.write("/** @file\n")
        f.write("  GUID names for the UEFI Handles and UEFI System windows.\n")
        f.write("  Generated by scripts/gen-guids.py from the edk2 DEC files; do not edit.\n\n")
        f.write("  Copyright (c) 2026, Niall Tseng. All rights reserved.<BR>\n")
        f.write("  SPDX-License-Identifier: BSD-2-Clause-Patent\n**/\n\n")
        f.write('#include "RwCoreInternal.h"\n\n')
        f.write("CONST RW_GUID_NAME  gRwGuidNames[] = {\n")
        for (d1, d2, d3, d4), name in rows:
            b = ", ".join("0x%02X" % x for x in d4)
            f.write('  { { 0x%08X, 0x%04X, 0x%04X, { %s } }, "%s" },\n' % (d1, d2, d3, b, name))
        f.write("};\n\n")
        f.write("CONST UINTN  gRwGuidNameCount = ARRAY_SIZE (gRwGuidNames);\n")
    print("%d GUIDs" % len(rows))


if __name__ == "__main__":
    main()
